const { test, after } = require('node:test');
const assert = require('node:assert/strict');
const qa = require('../support/feature-qa.cjs');
const { validateAdjustment, applyAdjustment } = require('../../dist/src/modules/ajustes/ajustes.service');
const input = (amount, tipo='SALIDA') => validateAdjustment({ idBodega: 1, observacion: 'Diferencia conteo QA', detalles: [{ idProducto: 1, tipo, cantidad: amount }] });
test('F01 SQL Server: atomic adjustments, missing stock, rollback and simultaneous withdrawals', async () => {
  const db = await qa.setup('F01');
  await db.query('UPDATE INVENTARIO.Existencia SET Stock=10 WHERE IdBodega=1 AND IdProducto=1');
  let r = await db.transaction(m=>applyAdjustment(m,input(3,'ENTRADA'),1));
  assert.equal(r.detalles[0].stockPosterior,'13.00');
  r = await db.transaction(m=>applyAdjustment(m,input(4),1)); assert.equal(r.detalles[0].stockPosterior,'9.00');
  const before = await db.query('SELECT COUNT(*) AS n FROM INVENTARIO.Ajuste');
  const mixed = validateAdjustment({ idBodega: 1, observacion: 'Rollback conjunto QA', detalles: [{ idProducto: 1, tipo: 'ENTRADA', cantidad: 1 }, { idProducto: 2, tipo: 'SALIDA', cantidad: 99 }] });
  await assert.rejects(db.transaction(m=>applyAdjustment(m,mixed,1)), { status: 409 });
  assert.deepEqual(await db.query('SELECT COUNT(*) AS n FROM INVENTARIO.Ajuste'),before);
  assert.equal((await db.query('SELECT Stock FROM INVENTARIO.Existencia WHERE IdBodega=1 AND IdProducto=1'))[0].Stock,9);
  await db.query('UPDATE INVENTARIO.Existencia SET Stock=10 WHERE IdBodega=1 AND IdProducto=1');
  const competing = await Promise.allSettled([1,2].map(()=>db.transaction(m=>applyAdjustment(m,input(7),1))));
  assert.equal(competing.filter(r=>r.status==='fulfilled').length,1);
  assert.equal(competing.find(r=>r.status==='rejected').reason.status,409);
  assert.equal((await db.query('SELECT Stock FROM INVENTARIO.Existencia WHERE IdBodega=1 AND IdProducto=1'))[0].Stock,3);
  const missing = validateAdjustment({ idBodega: 1, observacion: 'Existencia nueva QA', detalles: [{ idProducto: 27, tipo: 'ENTRADA', cantidad: 2 }] });
  await db.transaction(m=>applyAdjustment(m,missing,1));
  assert.equal((await db.query('SELECT Stock FROM INVENTARIO.Existencia WHERE IdBodega=1 AND IdProducto=27'))[0].Stock,2);
  const countBeforeFailure = await db.query('SELECT COUNT(*) AS n FROM INVENTARIO.Ajuste');
  await db.query("CREATE TRIGGER INVENTARIO.QA_FalloAjusteKardex ON INVENTARIO.Kardex AFTER INSERT AS THROW 51000,'QA fallo Kardex ajuste',1");
  await assert.rejects(db.transaction(m=>applyAdjustment(m,input(1,'ENTRADA'),1)));
  await db.query('DROP TRIGGER INVENTARIO.QA_FalloAjusteKardex');
  assert.deepEqual(await db.query('SELECT COUNT(*) AS n FROM INVENTARIO.Ajuste'),countBeforeFailure);
  assert.equal((await db.query('SELECT Stock FROM INVENTARIO.Existencia WHERE IdBodega=1 AND IdProducto=1'))[0].Stock,3);
  await qa.authChecks([['POST','/ajustes'],['GET','/ajustes'],['GET','/ajustes/1']]);
});
after(qa.cleanup);
