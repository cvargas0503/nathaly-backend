const { test, after } = require('node:test');
const assert = require('node:assert/strict');
const qa = require('../support/feature-qa.cjs');
const { listNotifications, readNotification } = require('../../dist/src/modules/notificaciones/notificaciones.service');
test('F03 SQL Server: private reads, ten concurrent GETs, episodes and complete unread counts', async () => {
  const db = await qa.setup('F03');
  await db.query('UPDATE INVENTARIO.Existencia SET Stock=3 WHERE IdBodega=2 AND IdProducto=1');
  const lists = await Promise.all(Array.from({length:10},()=>db.transaction(m=>listNotifications(m,1,{}))));
  assert.ok(lists.every(r=>r.noLeidas===27 && r.pagination.total===27 && r.data.length===20));
  const episode = (await db.query("SELECT CONVERT(varchar(30),IdNotificacion) AS id,Fecha FROM ADMIN.Notificacion WHERE ClaveCondicion='stock-1-1' AND Activa=1"))[0];
  await Promise.all([1,2].map(()=>db.transaction(m=>readNotification(m,1,episode.id))));
  const a = await db.transaction(m=>listNotifications(m,1,{leida:'false',limit:'100'}));
  const b = await db.transaction(m=>listNotifications(m,2,{limit:'100'}));
  assert.equal(a.noLeidas,26); assert.equal(b.noLeidas,27);
  assert.equal(b.data.find(n=>n.id===episode.id).leida,false);
  assert.equal((await db.query('SELECT COUNT(*) AS n FROM ADMIN.NotificacionLectura WHERE IdNotificacion=@0 AND UsuarioId=1',[episode.id]))[0].n,1);
  await db.query("INSERT INTO ADMIN.Notificacion (Tipo,Titulo,UsuarioId,Leida,Fecha,Activa) VALUES ('privada','Privada B',2,0,SYSUTCDATETIME(),1)");
  const [privateMessage] = await db.query("SELECT CONVERT(varchar(30),IdNotificacion) AS id FROM ADMIN.Notificacion WHERE UsuarioId=2");
  await assert.rejects(db.transaction(m=>readNotification(m,1,privateMessage.id)),{status:404});
  await db.query('UPDATE INVENTARIO.Existencia SET Stock=20 WHERE IdBodega=1 AND IdProducto=1');
  await db.transaction(m=>listNotifications(m,1,{}));
  assert.equal((await db.query('SELECT Activa FROM ADMIN.Notificacion WHERE IdNotificacion=@0',[episode.id]))[0].Activa,false);
  await db.query('UPDATE INVENTARIO.Existencia SET Stock=3 WHERE IdBodega=1 AND IdProducto=1');
  await db.transaction(m=>listNotifications(m,1,{}));
  const current = (await db.query("SELECT CONVERT(varchar(30),IdNotificacion) AS id FROM ADMIN.Notificacion WHERE ClaveCondicion='stock-1-1' AND Activa=1"))[0];
  assert.notEqual(current.id,episode.id);
  await db.query("CREATE TRIGGER ADMIN.QA_FalloLectura ON ADMIN.NotificacionLectura AFTER INSERT AS THROW 51000,'QA fallo lectura',1");
  await assert.rejects(db.transaction(m=>readNotification(m,2,current.id)));
  await db.query('DROP TRIGGER ADMIN.QA_FalloLectura');
  assert.equal((await db.query('SELECT COUNT(*) AS n FROM ADMIN.NotificacionLectura WHERE IdNotificacion=@0 AND UsuarioId=2',[current.id]))[0].n,0);
  await db.transaction(m=>readNotification(m,2,'stock-1-1'));
  await qa.authChecks([['GET','/notificaciones'],['PATCH','/notificaciones/1/leer']]);
});
after(qa.cleanup);
