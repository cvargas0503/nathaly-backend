const { test, after } = require('node:test');
const assert = require('node:assert/strict');
const qa = require('../support/feature-qa.cjs');
const { validateReturn, applyReturn, availabilitySQL } = require('../../dist/src/modules/devoluciones/devoluciones.service');
const input = (cantidad, explicit=true) => validateReturn({ idVenta: '1', motivo: 'Producto devuelto QA', detalles: [{ ...(explicit?{idVentaDetalle:'1'}:{idProducto:1}), cantidad }] });
test('F02 SQL Server: accumulated balance, retries, ambiguity, concurrency and full rollback', async () => {
  const db = await qa.setup('F02');
  await qa.insert('VENTAS.Venta',{ NumeroVenta: 'QA-VENTA', IdBodega: 1, Eliminado: false });
  await qa.insert('VENTAS.VentaDetalle',{ IdVenta: 1, IdProducto: 1, Cantidad: '10.00', PrecioUnitario: '20.0000', Eliminado: false });
  await db.transaction(m=>applyReturn(m,input(3,false),1,null));
  assert.equal((await db.query(availabilitySQL,['1']))[0].disponible,'7.00');
  await assert.rejects(db.transaction(m=>applyReturn(m,input(8),1,null)),{status:409});
  const first = await db.transaction(m=>applyReturn(m,input(4),1,'retry-demo'));
  const replay = await db.transaction(m=>applyReturn(m,input(4),1,'retry-demo'));
  assert.equal(replay.idNotaCredito,first.idNotaCredito); assert.equal(replay.replayed,true);
  assert.equal((await db.query(availabilitySQL,['1']))[0].disponible,'3.00');
  assert.equal((await db.query('SELECT COUNT(*) AS n FROM VENTAS.NotaCredito'))[0].n,2);
  await assert.rejects(db.transaction(m=>applyReturn(m,input(1),1,'retry-demo')),{status:409});
  // The same key from another user creates its own result.
  const other = await db.transaction(m=>applyReturn(m,input(1),2,'retry-demo')); assert.notEqual(other.idNotaCredito,first.idNotaCredito);
  const competing = await Promise.allSettled([1,2].map(()=>db.transaction(m=>applyReturn(m,input(2),1,null))));
  assert.equal(competing.filter(r=>r.status==='fulfilled').length,1);
  assert.equal(competing.find(r=>r.status==='rejected').reason.status,409);
  await qa.insert('VENTAS.VentaDetalle',{ IdVenta: 1, IdProducto: 1, Cantidad: '10.00', PrecioUnitario: '20.0000', Eliminado: false });
  await assert.rejects(db.transaction(m=>applyReturn(m,input(1,false),1,null)),{status:409});
  const secondLine = validateReturn({ idVenta:'1', motivo:'Rollback de Kardex', detalles:[{idVentaDetalle:'2',cantidad:1}] });
  const before = await db.query('SELECT ValorActual FROM ADMIN.Consecutivos WHERE Entidad=\'NOTA_CREDITO\'');
  const stock = await db.query('SELECT Stock FROM INVENTARIO.Existencia WHERE IdBodega=1 AND IdProducto=1');
  await db.query("CREATE TRIGGER INVENTARIO.QA_FalloKardex ON INVENTARIO.Kardex AFTER INSERT AS THROW 51000,'QA fallo Kardex',1");
  await assert.rejects(db.transaction(m=>applyReturn(m,secondLine,1,'rollback-demo')));
  await db.query('DROP TRIGGER INVENTARIO.QA_FalloKardex');
  assert.deepEqual(await db.query('SELECT ValorActual FROM ADMIN.Consecutivos WHERE Entidad=\'NOTA_CREDITO\''),before);
  assert.deepEqual(await db.query('SELECT Stock FROM INVENTARIO.Existencia WHERE IdBodega=1 AND IdProducto=1'),stock);
  assert.equal((await db.query("SELECT COUNT(*) AS n FROM ADMIN.SolicitudDevolucion WHERE Clave='rollback-demo'"))[0].n,0);
  await db.transaction(m=>applyReturn(m,secondLine,1,'rollback-demo'));
  await assert.rejects(db.query("INSERT INTO ADMIN.SolicitudDevolucion (UsuarioId,Clave,BodyHash,Resultado,Fecha) VALUES (1,'retry-demo',REPLICATE('0',64),'{}',SYSUTCDATETIME())"));
  await qa.authChecks([['POST','/devoluciones'],['GET','/devoluciones'],['GET','/devoluciones/1'],['GET','/devoluciones/ventas/1/disponibilidad']]);
});
after(qa.cleanup);
